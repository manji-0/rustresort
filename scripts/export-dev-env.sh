#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

HOST="${RUSTRESORT__SERVER__HOST:-127.0.0.1}"
PORT="${RUSTRESORT__SERVER__PORT:-3000}"
DOMAIN="${RUSTRESORT__SERVER__DOMAIN:-localhost:${PORT}}"
PROTOCOL="${RUSTRESORT__SERVER__PROTOCOL:-http}"
DB_PATH="${RUSTRESORT__DATABASE__PATH:-data/rustresort-dev.db}"
AUTH_USERNAME="${RUSTRESORT__AUTH__USERNAME:-admin}"
AUTH_PASSWORD="${RUSTRESORT__AUTH__PASSWORD:-admin-password}"
SESSION_SECRET="${RUSTRESORT__AUTH__SESSION_SECRET:-0123456789abcdef0123456789abcdef}"
INSTANCE_TITLE="${RUSTRESORT__INSTANCE__TITLE:-RustResort Dev UI}"
INSTANCE_DESCRIPTION="${RUSTRESORT__INSTANCE__DESCRIPTION:-Rust/WASM development instance}"
INSTANCE_CONTACT_EMAIL="${RUSTRESORT__INSTANCE__CONTACT_EMAIL:-admin@example.com}"
LOG_LEVEL="${RUSTRESORT__LOGGING__LEVEL:-debug}"
LOG_FORMAT="${RUSTRESORT__LOGGING__FORMAT:-pretty}"
UI_DEV_DIR="${RUSTRESORT__UI__DEV_DIR:-crates/rustresort-ui/dist}"

mkdir -p "$(dirname "$DB_PATH")"

export RUSTRESORT__SERVER__HOST="$HOST"
export RUSTRESORT__SERVER__PORT="$PORT"
export RUSTRESORT__SERVER__DOMAIN="$DOMAIN"
export RUSTRESORT__SERVER__PROTOCOL="$PROTOCOL"
export RUSTRESORT__DATABASE__PATH="$DB_PATH"
export RUSTRESORT__AUTH__USERNAME="$AUTH_USERNAME"
export RUSTRESORT__AUTH__PASSWORD="$AUTH_PASSWORD"
export RUSTRESORT__AUTH__SESSION_SECRET="$SESSION_SECRET"
export RUSTRESORT__INSTANCE__TITLE="$INSTANCE_TITLE"
export RUSTRESORT__INSTANCE__DESCRIPTION="$INSTANCE_DESCRIPTION"
export RUSTRESORT__INSTANCE__CONTACT_EMAIL="$INSTANCE_CONTACT_EMAIL"
export RUSTRESORT__LOGGING__LEVEL="$LOG_LEVEL"
export RUSTRESORT__LOGGING__FORMAT="$LOG_FORMAT"
export RUSTRESORT__UI__DEV_DIR="$UI_DEV_DIR"
